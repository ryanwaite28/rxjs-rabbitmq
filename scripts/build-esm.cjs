// Generates the ESM entry point as a thin wrapper around the CJS build, so ESM and CJS
// consumers share one module instance (no dual-package hazard: `instanceof` checks on
// error classes and the global serializer registry work across both import styles).
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const cjsEntry = path.join(root, 'dist/cjs/index.js');
const esmDir = path.join(root, 'dist/esm');

const names = Object.keys(require(cjsEntry)).filter((name) => name !== 'default' && name !== '__esModule').sort();

fs.rmSync(esmDir, { recursive: true, force: true });
fs.mkdirSync(esmDir, { recursive: true });

fs.writeFileSync(path.join(esmDir, 'index.mjs'), [
  '// Generated by scripts/build-esm.cjs. Do not edit.',
  "import cjs from '../cjs/index.js';",
  '',
  `export const {\n${names.map((name) => `  ${name},`).join('\n')}\n} = cjs;`,
  'export default cjs;',
  '',
].join('\n'));

fs.writeFileSync(path.join(esmDir, 'index.d.mts'), [
  '// Generated by scripts/build-esm.cjs. Do not edit.',
  "export * from '../cjs/index.js';",
  "import * as rxjsRabbitmq from '../cjs/index.js';",
  'export default rxjsRabbitmq;',
  '',
].join('\n'));

console.log(`dist/esm: re-exported ${names.length} runtime exports`);
